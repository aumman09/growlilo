export function Faq() {
  const [open, setOpen] = useState<number | null>(0);
  const base = useId();
  return (
    <div className="faq">
      {FAQS.map((f, i) => {
        const isOpen = open === i;
        return (
          <div key={f.q} className={`faq__item ${isOpen ? "is-open" : ""}`}>
            <h3>
              <button id={`${base}-q${i}`} aria-expanded={isOpen} aria-controls={`${base}-a${i}`} onClick={() => setOpen(isOpen ? null : i)}>
                <span>{f.q}</span><span className="faq__icon" aria-hidden />
              </button>
            </h3>
            <div id={`${base}-a${i}`} role="region" aria-labelledby={`${base}-q${i}`} hidden={!isOpen} className="faq__a">
              <p>{f.a}</p>
            </div>
          </div>
        );
      })}
    </div>
  );
}
